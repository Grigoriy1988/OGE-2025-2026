def Преобразователь(a, b, step, k=''):
    if step == 0:
        print(k + f" => {a}" + '  Ошибка' if a != b else k + f" => {a}" + "   ОТВЕТ")
        return
    if a % 4 == 0:
        Преобразователь(a - 1, b, step - 1, k + '1')
        Преобразователь(a // 4, b, step - 1, k + '2')
    else:
        Преобразователь(a - 1, b, step - 1, k + '1')


Преобразователь(53, 2, 5)
