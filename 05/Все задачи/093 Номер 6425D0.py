def Конструктор(a, b, step, k=''):
    if step == 0:
        print(k + f" => {a}" + '  Ошибка' if a != b else k + f" => {a}" + "   ОТВЕТ")
        return
    if a % 2 == 0:
        Конструктор(a * 10 + 2, b, step - 1, k + '1')
        Конструктор(a // 2, b, step - 1, k + '2')
    else:
        Конструктор(a * 10 + 2, b, step - 1, k + '2')


Конструктор(32, 21, 5)
